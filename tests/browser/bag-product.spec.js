import { test, expect } from '../fixtures/preview-page.js';
import manifest from '../../src/data/product-images.generated.json' with { type: 'json' };

for (const width of [375, 1440]) test(`Bag product content, gallery and recommendation at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 950 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', r => { if (r.url().includes('/productos/bag/') && r.status() >= 400) errors.push(r.url()); });
  await page.goto('/productos/estuche-transporte');
  await expect(page.locator('h1')).toHaveText('Estuche de transporte para R36S');
  await expect(page).toHaveTitle(/Estuche de transporte para R36S/);
  await expect(page.locator('.detail-copy')).toContainText('Protege tu consola y lleva tus accesorios organizados allá donde vayas.');
  await expect(page.locator('.bag-included-note')).toHaveText('Se incluye únicamente el estuche. Consola y accesorios no incluidos.');
  await expect(page.locator('.bag-single-color')).toHaveText('Color: Negro');
  await expect(page.locator('.variant-selector, select')).toHaveCount(0);
  await expect(page.locator('.thumbnails button')).toHaveCount(4);
  const sources = ['cajat', 'cajcerrada', 'cajasola', 'todo'];
  for (let i = 0; i < sources.length; i++) {
    await page.locator('.thumbnails button').nth(i).click();
    const image = manifest.products['estuche-transporte'].find(image => image.source === sources[i]);
    const main = page.locator('.gallery-main img');
    await expect(main).toHaveAttribute('src', '/' + image.src);
    await expect.poll(() => main.evaluate(i => i.complete && i.naturalWidth > 0)).toBe(true);
  }
  await page.locator('.thumbnails button').first().click();
  await page.locator('.gallery-main').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('.bag-feature')).toHaveCount(4);
  await expect(page.locator('.bag-specifications')).not.toHaveAttribute('open', '');
  await page.locator('.bag-specifications summary').click();
  await expect(page.locator('.bag-spec-content')).toBeVisible();
  await expect(page.locator('.bag-spec-content')).toContainText('15,24 × 10,54 × 5,51 cm');
  await expect(page.locator('.bag-spec-content')).toContainText('0,6 kg');
  await expect(page.locator('.bag-spec-content')).toContainText('EVA');
  await expect(page.locator('.bag-compatibility li')).toHaveText(['R36S', 'RG353V', 'RG353VS', 'RG35XX']);
  await expect(page.locator('.bag-compatibility')).toContainText('R36H Air no está verificada');
  await expect(page.locator('main')).not.toContainText('10 × 8 × 3');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/bag-product-${width}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Añadir al carrito ↗' }).click();
  await expect(page).toHaveURL(/\/carrito$/);
  await expect(page.locator('.cart-line')).toContainText('Estuche de transporte');
  await page.goto('/productos/r36s');
  const recommendation = page.locator('.bag-recommendation');
  await expect(recommendation).toContainText('Ajuste pendiente de comprobar');
  await expect(recommendation.locator('button')).toHaveCount(0);
  await expect(page.locator('.variant-options button')).toHaveCount(13);
  const image = recommendation.locator('img');
  await image.scrollIntoViewIfNeeded();
  await expect.poll(() => image.evaluate(i => i.complete && i.naturalWidth > 0)).toBe(true);
  await recommendation.screenshot({ path: `test-results/bag-recommendation-${width}.png` });
  await recommendation.getByRole('link', { name: 'Ver estuche' }).click();
  await expect(page).toHaveURL(/\/productos\/estuche-transporte$/);
  await page.goto('/productos/r36h');
  await expect(page.locator('.bag-recommendation, .bag-details')).toHaveCount(0);
  await expect(page.locator('h1')).toContainText('R36H Air');
  expect(errors).toEqual([]);
});
